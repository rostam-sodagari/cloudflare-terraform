"""Configure a root backend without reconfiguring or migrating state."""
import os


def backend_setup(r, backend, repository_root, fail):
    """Point a root at the chosen backend; return extra `terraform init` args."""
    override = r.dir / "backend_override.tf"
    if backend == "local":
        if os.environ.get("CI"):
            fail("BACKEND=local is not allowed in CI; CI always uses R2")
        (repository_root / ".state" / "domains").mkdir(parents=True, exist_ok=True)
        text = ("# Generated by cf.py for --backend local. Git-ignored; do not edit.\n"
                "terraform {\n  backend \"local\" {\n"
                f"    path = \"{r.rel}/.state/{r.key}\"\n  }}\n}}\n")
        override.write_text(text, encoding="utf-8", newline="\n")
        return []
    override.unlink(missing_ok=True)
    backend_hcl = repository_root / "backend.hcl"
    if not backend_hcl.exists():
        fail("Missing backend.hcl: copy backend.hcl.example to backend.hcl and fill it in")
    return [f"-backend-config={backend_hcl}", f"-backend-config=key={r.key}"]
