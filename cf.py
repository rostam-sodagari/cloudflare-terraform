def cmd_lint(a):
    rc = run_tf([f"-chdir={ROOT}", "fmt", "-recursive", "-check"]).returncode
    if rc != 0:
        sys.exit(rc)
    sys.exit(run_py("validate.py", ["--all"]).returncode)


def cmd_domains(a):
    for d in domains():
        print(d)


def cmd_new(a):
    if not HOSTRE.match(a.domain):
        fail("domain name must be a valid hostname (letters, digits, hyphens, dots)")
    if not HEX32.match(a.zone_id):
        fail("zone id must be 32 hex characters")
    dest = ROOT / "domains" / a.domain
    if dest.exists():
        fail(f"{dest} already exists")
    shutil.copytree(ROOT / "domains" / "_template", dest)
    (dest / "README.md").unlink(missing_ok=True)
    (dest / "domain.yaml").write_text(
        f'name: {a.domain}\nzone_id: "{a.zone_id}"\nplan: {a.plan}\nowner: change-me\n',
        encoding="utf-8", newline="\n")
    print(green(f"Created {dest}. Fill in the YAML files, then: python3 cf.py plan {a.domain}"))


def cmd_export(a):
    args = ["--zone-id", a.zone_id, "--domain", a.domain]
    if a.force:
        args.append("--force")
    if a.plan:
        args += ["--plan", a.plan]
    sys.exit(run_py("export_zone.py", args).returncode)


def cmd_export_account(a):
    args = ["--account-id", a.account_id]
    if a.plan:
        args += ["--plan", a.plan]
    sys.exit(run_py("export_zone.py", args).returncode)


# ---- roots to plan since a git ref (used by CI) ---------------------------
def _is_example(path):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    return re.search(r"^example:\s*true", text, re.MULTILINE) is not None


def all_roots():
    out = []
    if not _is_example(ROOT / "account" / "account.yaml"):
        out.append("account")
    out += [d for d in domains() if not _is_example(ROOT / "domains" / d / "domain.yaml")]
    return out


def _git_diff(*args):
    return subprocess.run(["git", "diff", "--name-only", *args], cwd=ROOT,
                          capture_output=True, text=True).stdout


def changed_roots(base, want_all):
    if want_all:
        return all_roots()
    changed = _git_diff(f"{base or 'origin/main'}...HEAD") or _git_diff("HEAD~1", "HEAD")
    lines = [l for l in changed.splitlines() if l]
    if not lines or any(re.match(r"^(modules|scripts)/", l) or
                         l in {"policy.yaml", "backend.hcl.example"} for l in lines):
        return all_roots()  # shared code changed, or history unavailable: plan everything
    wanted = {"account"} if any(l.startswith("account/") for l in lines) else set()
    for l in lines:
        m = re.match(r"^domains/([^/]+)", l)
        if m:
            wanted.add(m.group(1))
    return [r for r in all_roots() if r in wanted]


def cmd_changed_domains(a):
    print(json.dumps(changed_roots(a.base, a.all)))


# ---- CLI wiring -------------------------------------------------------------
PLANS = ["free", "pro", "business", "enterprise"]


def subcmd(sub, name, fn, **kw):
    """Add a subparser wired to fn, with a domain/account positional unless root=False."""
    root = kw.pop("root", True)
    p = sub.add_parser(name, **kw)
    p.set_defaults(fn=fn)
    if root:
        p.add_argument("domain", help="a folder name under domains/, or 'account'")
    return p


def add_backend_arg(p):
    p.add_argument("--backend", choices=["local", "r2"], help="default: $CF_BACKEND, else r2")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command")

    sub.add_parser("help", help="show this message")

    subcmd(sub, "validate", cmd_validate)
    subcmd(sub, "validate-all", cmd_validate_all, root=False)

    add_backend_arg(subcmd(sub, "init", cmd_init))
    add_backend_arg(subcmd(sub, "plan", cmd_plan))

    p = subcmd(sub, "apply", cmd_apply)
    p.add_argument("--yes", action="store_true")

    p = subcmd(sub, "deviation-check", cmd_deviation_check)
    add_backend_arg(p)
    p.add_argument("--deviation-exit", action="store_true", help="exit 2 when deviation exists (else always exit 0)")

    p = subcmd(sub, "migrate", cmd_migrate)
    p.add_argument("--to", choices=["local", "r2"])

    subcmd(sub, "test", cmd_test)
    subcmd(sub, "test-all", cmd_test_all, root=False)
    subcmd(sub, "unit", cmd_unit, root=False)
    subcmd(sub, "fmt", cmd_fmt, root=False)
    subcmd(sub, "lint", cmd_lint, root=False)
    subcmd(sub, "domains", cmd_domains, root=False)

    p = subcmd(sub, "new", cmd_new, root=False)
    p.add_argument("domain", help="name of the new domain, e.g. example.org")
    p.add_argument("--zone-id", required=True)
    p.add_argument("--plan", required=True, choices=PLANS)

    p = subcmd(sub, "export", cmd_export, root=False)
    p.add_argument("domain", help="domain to export into, e.g. example.org")
    p.add_argument("--zone-id", required=True)
    p.add_argument("--force", action="store_true")
    p.add_argument("--plan", choices=PLANS)

    p = subcmd(sub, "export-account", cmd_export_account, root=False)
    p.add_argument("--account-id", required=True)
    p.add_argument("--plan", choices=PLANS)

    p = subcmd(sub, "changed-domains", cmd_changed_domains, root=False)
    p.add_argument("base", nargs="?", default=None, help="git ref to diff against (default origin/main)")
    p.add_argument("--all", action="store_true")

    a = ap.parse_args()
