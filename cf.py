#!/usr/bin/env python3
"""
Cloudflare Terraform helper. The one entry point for this repository: works
the same on macOS, Linux and Windows wherever Python 3 and Terraform are
installed. Run `python3 cf.py help` for the full list.

Everyday (people who edit YAML):
  python3 cf.py validate example.com        check the YAML; no token needed
  python3 cf.py plan example.com            show exactly what would change in Cloudflare
  python3 cf.py apply example.com           apply the plan you just reviewed (asks you to confirm)
  python3 cf.py drift example.com           list changes made outside Git since the last apply

Setting up domains:
  python3 cf.py new example.org --zone-id <id> --plan pro
  python3 cf.py export example.org --zone-id <id> [--force]   copy a live zone into YAML (read-only)
  python3 cf.py export-account --account-id <id> [--plan pro]

Maintainers:
  python3 cf.py test <domain|account> | test-all | unit | validate-all | fmt | lint | domains
  python3 cf.py migrate <domain|account> --to local|r2         move state between backends
  python3 cf.py changed-domains [--all | <git-ref>]            roots to plan since a ref (used by CI)

Use "account" instead of a domain name for account-level lists.
State goes to R2 by default. Pass --backend local, or set CF_BACKEND=local,
to keep it on this machine in .state/. Set TF=tofu (environment variable) to
use OpenTofu instead of Terraform.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent
SCRIPTS = ROOT / "scripts"
TF = os.environ.get("TF", "terraform")
HEX32 = re.compile(r"^[0-9a-f]{32}$")
HOSTRE = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$")


def fail(msg) -> NoReturn:
    sys.exit(msg)


def run_py(script, args, capture=False):
    kw = dict(capture_output=True, text=True) if capture else {}
    return subprocess.run([sys.executable, str(SCRIPTS / script), *args], **kw)


def run_tf(args, capture=False):
    kw = dict(capture_output=True, text=True) if capture else {}
    try:
        return subprocess.run([TF, *args], **kw)
    except FileNotFoundError:
        fail(f"'{TF}' not found on PATH. Install Terraform "
             "(https://developer.hashicorp.com/terraform/install), or set TF=tofu to use OpenTofu.")


# --------------------------------------------------------------------------
class Rt:
    """One root to operate on: a domain folder, or 'account'."""

    def __init__(self, name):
        self.name = name
        if name == "account":
            self.dir = ROOT / "account"
            self.key = "account.tfstate"
            self.rel = ".."
        else:
            self.dir = ROOT / "domains" / name
            self.key = f"domains/{name}.tfstate"
            self.rel = "../.."
        if not self.dir.is_dir():
            fail(f"No such folder: {self.dir}")


def domains():
    return sorted(p.name for p in (ROOT / "domains").iterdir() if p.is_dir() and not p.name.startswith("_"))


def resolve_backend(a):
    backend = getattr(a, "backend", None) or os.environ.get("CF_BACKEND", "r2").lower()
    if backend not in ("local", "r2"):
        fail(f"CF_BACKEND must be local or r2, not '{backend}'")
    return backend


# ---- backend / init -------------------------------------------------------
def backend_setup(r, backend):
    """Point a root at the chosen backend; return extra `terraform init` args."""
    override = r.dir / "backend_override.tf"
    if backend == "local":
        if os.environ.get("CI"):
            fail("BACKEND=local is not allowed in CI; CI always uses R2")
        (ROOT / ".state" / "domains").mkdir(parents=True, exist_ok=True)
        text = ("# Generated by cf.py for --backend local. Git-ignored; do not edit.\n"
                "terraform {\n  backend \"local\" {\n"
                f"    path = \"{r.rel}/.state/{r.key}\"\n  }}\n}}\n")
        override.write_text(text, encoding="utf-8", newline="\n")
        return []
    override.unlink(missing_ok=True)
    backend_hcl = ROOT / "backend.hcl"
    if not backend_hcl.exists():
        fail("Missing backend.hcl: copy backend.hcl.example to backend.hcl and fill it in")
    return [f"-backend-config={backend_hcl}", f"-backend-config=key={r.key}"]


def tf_init(r, backend):
    """Never uses -reconfigure: if the backend differs from the one this root
    was last initialised with, Terraform stops and `migrate` is needed instead
    of silently losing track of the existing state."""
    extra = backend_setup(r, backend)
    proc = run_tf([f"-chdir={r.dir}", "init", "-input=false", *extra], capture=True)
    (r.dir / ".init.log").write_text(proc.stdout + proc.stderr, encoding="utf-8")
    if proc.returncode != 0:
        print(proc.stdout + proc.stderr)
        print(f"\nIf Terraform says the backend changed, run: python3 cf.py migrate {r.name} --to {backend}")
        sys.exit(proc.returncode)


def validate(r):
    target = "account" if r.name == "account" else str(r.dir)
    rc = run_py("validate.py", [target]).returncode
    if rc != 0:
        sys.exit(rc)


def warning_lines(log_text):
    """Mirrors `grep -E "^(Warning|Error):" -A3 | grep -v "dry run"`: surface
    provider warnings/errors even on an otherwise successful plan."""
    lines = log_text.splitlines()
    picked = set()
    for i, l in enumerate(lines):
        if re.match(r"^(Warning|Error):", l):
            picked.update(range(i, min(i + 4, len(lines))))
    return [lines[i] for i in sorted(picked) if "dry run" not in lines[i]]


# ---- commands --------------------------------------------------------------
def cmd_validate(a):
    target = "account" if a.domain == "account" else str(Rt(a.domain).dir)
    sys.exit(run_py("validate.py", [target]).returncode)


def cmd_validate_all(a):
    sys.exit(run_py("validate.py", ["--all"]).returncode)


def cmd_init(a):
    tf_init(Rt(a.domain), resolve_backend(a))


def cmd_plan(a):
    r = Rt(a.domain)
    backend = resolve_backend(a)
    validate(r)
    tf_init(r, backend)
    for f in ("plan.bin", "plan.json"):
        (r.dir / f).unlink(missing_ok=True)
    print(f"Planning {r.name} (reads Cloudflare, changes nothing) ...")
    proc = run_tf([f"-chdir={r.dir}", "plan", "-input=false", "-lock-timeout=60s", "-out=plan.bin"], capture=True)
    log = proc.stdout + proc.stderr
    (r.dir / "plan.log").write_text(log, encoding="utf-8")
    if proc.returncode != 0:
        print(log)
        sys.exit(proc.returncode)
    for line in warning_lines(log):
        print(line)
    show = run_tf([f"-chdir={r.dir}", "show", "-json", "plan.bin"], capture=True)
    (r.dir / "plan.json").write_text(show.stdout, encoding="utf-8")
    md = run_py("plan_summary.py", [str(r.dir / "plan.json"), "--root", r.name, "--format", "md"], capture=True)
    (r.dir / "plan-summary.md").write_text(md.stdout, encoding="utf-8")
    run_py("plan_summary.py", [str(r.dir / "plan.json"), "--root", r.name])
    print()
    print(f"Full Terraform output: {r.dir}/plan.log   Summary for the PR: {r.dir}/plan-summary.md")


def cmd_apply(a):
    r = Rt(a.domain)
    if not (r.dir / "plan.bin").exists():
        fail(f"No saved plan. Run: python3 cf.py plan {r.name}")
    run_py("plan_summary.py", [str(r.dir / "plan.json"), "--root", r.name])
    yes = a.yes or os.environ.get("YES") == "1"
    if not os.environ.get("CI") and not yes:
        ans = input(f"\nType the name '{r.name}' to apply exactly these changes: ")
        if ans != r.name:
            fail("Cancelled. Nothing was changed.")
    proc = run_tf([f"-chdir={r.dir}", "apply", "-input=false", "plan.bin"])
    if proc.returncode != 0:
        sys.exit(proc.returncode)
    for f in ("plan.bin", "plan.json"):
        (r.dir / f).unlink(missing_ok=True)
    print(f"Applied. Run 'python3 cf.py plan {r.name}': it should now say 'Nothing will change'.")


def cmd_drift(a):
    r = Rt(a.domain)
    tf_init(r, resolve_backend(a))
    proc = run_tf([f"-chdir={r.dir}", "plan", "-refresh-only", "-input=false",
                   "-lock-timeout=60s", "-out=drift.bin"], capture=True)
    (r.dir / "drift.log").write_text(proc.stdout + proc.stderr, encoding="utf-8")
    if proc.returncode != 0:
        print(proc.stdout + proc.stderr)
        sys.exit(proc.returncode)
    show = run_tf([f"-chdir={r.dir}", "show", "-json", "drift.bin"], capture=True)
    (r.dir / "drift.json").write_text(show.stdout, encoding="utf-8")
    (r.dir / "drift.bin").unlink(missing_ok=True)
    rc = run_py("plan_summary.py", [str(r.dir / "drift.json"), "--root", r.name, "--drift-only"]).returncode
    if a.drift_exit:
        sys.exit(rc)


def cmd_migrate(a):
    r = Rt(a.domain)
    if not a.to:
        fail("python3 cf.py migrate <domain|account> --to local|r2")
    extra = backend_setup(r, a.to)
    # Interactive on purpose: Terraform asks before copying state.
    proc = run_tf([f"-chdir={r.dir}", "init", "-migrate-state", *extra])
    if proc.returncode != 0:
        sys.exit(proc.returncode)
    print(f"Done. Run: python3 cf.py plan {r.name} --backend {a.to}   (expect No changes)")


def test_one(r):
    """imports.tf is set aside: mocked providers cannot import, and import
    blocks only matter for a real plan."""
    validate(r)
    imports, parked = r.dir / "imports.tf", r.dir / ".imports.tf.skip"
    moved = imports.exists()
    if moved:
        imports.rename(parked)
    try:
        proc = run_tf([f"-chdir={r.dir}", "init", "-backend=false", "-input=false"], capture=True)
        if proc.returncode != 0:
            print(proc.stdout + proc.stderr)
            raise SystemExit(proc.returncode)
        if run_tf([f"-chdir={r.dir}", "test"]).returncode != 0:
            raise SystemExit(1)
    finally:
        if moved:
            parked.rename(imports)


def cmd_test(a):
    test_one(Rt(a.domain))


def cmd_test_all(a):
    failed = []
    for name in ["account"] + domains():
        print(f"== {name}")
        try:
            test_one(Rt(name))
        except SystemExit:
            failed.append(name)
    if failed:
        fail(f"Failed: {', '.join(failed)}")


def cmd_unit(a):
    sys.exit(subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"]).returncode)


def cmd_fmt(a):
    sys.exit(run_tf([f"-chdir={ROOT}", "fmt", "-recursive"]).returncode)


def cmd_lint(a):
    rc = run_tf([f"-chdir={ROOT}", "fmt", "-recursive", "-check"]).returncode
    if rc != 0:
        sys.exit(rc)
    sys.exit(run_py("validate.py", ["--all"]).returncode)


def cmd_domains(a):
    for d in domains():
        print(d)


def cmd_new(a):
    if not HOSTRE.match(a.domain):
        fail("domain name must be a valid hostname (letters, digits, hyphens, dots)")
    if not HEX32.match(a.zone_id):
        fail("zone id must be 32 hex characters")
    dest = ROOT / "domains" / a.domain
    if dest.exists():
        fail(f"{dest} already exists")
    shutil.copytree(ROOT / "domains" / "_template", dest)
    (dest / "README.md").unlink(missing_ok=True)
    (dest / "domain.yaml").write_text(
        f'name: {a.domain}\nzone_id: "{a.zone_id}"\nplan: {a.plan}\nowner: change-me\n',
        encoding="utf-8", newline="\n")
    print(f"Created {dest}. Fill in the YAML files, then: python3 cf.py plan {a.domain}")


def cmd_export(a):
    args = ["--zone-id", a.zone_id, "--domain", a.domain]
    if a.force:
        args.append("--force")
    if a.plan:
        args += ["--plan", a.plan]
    sys.exit(run_py("export_zone.py", args).returncode)


def cmd_export_account(a):
    args = ["--account-id", a.account_id]
    if a.plan:
        args += ["--plan", a.plan]
    sys.exit(run_py("export_zone.py", args).returncode)


# ---- roots to plan since a git ref (used by CI) ---------------------------
def _is_example(path):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    return re.search(r"^example:\s*true", text, re.MULTILINE) is not None


def all_roots():
    out = []
    if not _is_example(ROOT / "account" / "account.yaml"):
        out.append("account")
    out += [d for d in domains() if not _is_example(ROOT / "domains" / d / "domain.yaml")]
    return out


def _git_diff(*args):
    return subprocess.run(["git", "diff", "--name-only", *args], cwd=ROOT,
                          capture_output=True, text=True).stdout


def changed_roots(base, want_all):
    if want_all:
        return all_roots()
    changed = _git_diff(f"{base or 'origin/main'}...HEAD") or _git_diff("HEAD~1", "HEAD")
    lines = [l for l in changed.splitlines() if l]
    if not lines or any(re.match(r"^(modules|scripts)/", l) for l in lines):
        return all_roots()  # shared code changed, or history unavailable: plan everything
    wanted = {"account"} if any(l.startswith("account/") for l in lines) else set()
    for l in lines:
        m = re.match(r"^domains/([^/]+)", l)
        if m:
            wanted.add(m.group(1))
    return [r for r in all_roots() if r in wanted]


def cmd_changed_domains(a):
    print(json.dumps(changed_roots(a.base, a.all)))


# ---- CLI wiring -------------------------------------------------------------
def add_root_arg(p):
    p.add_argument("domain", help="a folder name under domains/, or 'account'")


def add_backend_arg(p):
    p.add_argument("--backend", choices=["local", "r2"], help="default: $CF_BACKEND, else r2")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command")

    sub.add_parser("help", help="show this message")

    p = sub.add_parser("validate"); add_root_arg(p); p.set_defaults(fn=cmd_validate)
    sub.add_parser("validate-all").set_defaults(fn=cmd_validate_all)

    p = sub.add_parser("init"); add_root_arg(p); add_backend_arg(p); p.set_defaults(fn=cmd_init)
    p = sub.add_parser("plan"); add_root_arg(p); add_backend_arg(p); p.set_defaults(fn=cmd_plan)
    p = sub.add_parser("apply"); add_root_arg(p); p.add_argument("--yes", action="store_true"); p.set_defaults(fn=cmd_apply)
    p = sub.add_parser("drift"); add_root_arg(p); add_backend_arg(p)
    p.add_argument("--drift-exit", action="store_true", help="exit 2 when drift exists (else always exit 0)")
    p.set_defaults(fn=cmd_drift)
    p = sub.add_parser("migrate"); add_root_arg(p); p.add_argument("--to", choices=["local", "r2"]); p.set_defaults(fn=cmd_migrate)

    p = sub.add_parser("test"); add_root_arg(p); p.set_defaults(fn=cmd_test)
    sub.add_parser("test-all").set_defaults(fn=cmd_test_all)
    sub.add_parser("unit").set_defaults(fn=cmd_unit)
    sub.add_parser("fmt").set_defaults(fn=cmd_fmt)
    sub.add_parser("lint").set_defaults(fn=cmd_lint)
    sub.add_parser("domains").set_defaults(fn=cmd_domains)

    p = sub.add_parser("new")
    p.add_argument("domain"); p.add_argument("--zone-id", required=True)
    p.add_argument("--plan", required=True, choices=["free", "pro", "business", "enterprise"])
    p.set_defaults(fn=cmd_new)

    p = sub.add_parser("export")
    p.add_argument("domain"); p.add_argument("--zone-id", required=True)
    p.add_argument("--force", action="store_true")
    p.add_argument("--plan", choices=["free", "pro", "business", "enterprise"])
    p.set_defaults(fn=cmd_export)

    p = sub.add_parser("export-account")
    p.add_argument("--account-id", required=True)
    p.add_argument("--plan", choices=["free", "pro", "business", "enterprise"])
    p.set_defaults(fn=cmd_export_account)

    p = sub.add_parser("changed-domains")
    p.add_argument("base", nargs="?", default=None, help="git ref to diff against (default origin/main)")
    p.add_argument("--all", action="store_true")
    p.set_defaults(fn=cmd_changed_domains)

    a = ap.parse_args()
    if not a.command or a.command == "help":
        ap.print_help()
        return
    a.fn(a)


if __name__ == "__main__":
    main()
